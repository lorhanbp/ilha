import AppKit

struct ClipItem: Codable, Identifiable, Equatable {
    var id = UUID()
    var date: Date
    var text: String?
    var imageFile: String?
    var imageSize: String?
}

/// Guarda as últimas cópias (texto e imagem) e apaga cada uma depois do prazo dos Ajustes.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var copiedID: UUID?

    private let directory: URL
    private let indexFile: URL
    private var limit: Int { Settings.shared.clipboardLimit }
    private var lifetime: TimeInterval { TimeInterval(Settings.shared.clipboardHours) * 3600 }
    private var lastChange = NSPasteboard.general.changeCount
    private var ownChange: Int?
    private var thumbnails: [UUID: NSImage] = [:]
    private let sensitive: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                          "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    init() {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        directory = support.appendingPathComponent("Ilha/Clipboard")
        indexFile = directory.appendingPathComponent("items.json")
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        if let data = try? Data(contentsOf: indexFile), let saved = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = saved
        }
        purge()
        Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        Timer.scheduledTimer(withTimeInterval: 60, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.purge() }
        }
    }

    func thumbnail(for item: ClipItem) -> NSImage? {
        if let cached = thumbnails[item.id] { return cached }
        guard let file = item.imageFile, let image = NSImage(contentsOf: directory.appendingPathComponent(file)) else { return nil }
        thumbnails[item.id] = image
        return image
    }

    func copy(_ item: ClipItem) {
        let board = NSPasteboard.general
        board.clearContents()
        if let text = item.text {
            board.setString(text, forType: .string)
        } else if let file = item.imageFile, let image = NSImage(contentsOf: directory.appendingPathComponent(file)) {
            board.writeObjects([image])
        }
        ownChange = board.changeCount
        lastChange = board.changeCount
        copiedID = item.id
        Task { [weak self] in
            try? await Task.sleep(nanoseconds: 1_000_000_000)
            self?.copiedID = nil
        }
    }

    func clear() {
        items.forEach(deleteFile)
        items = []
        thumbnails = [:]
        save()
    }

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        if ownChange == lastChange { return }
        let types = board.types ?? []
        if types.contains(where: { sensitive.contains($0.rawValue) }) { return }

        if let text = board.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            items.removeAll { if $0.text == text { deleteFile($0); return true } else { return false } }
            insert(ClipItem(date: Date(), text: text))
        } else if let png = pngData(from: board) {
            let name = UUID().uuidString + ".png"
            guard (try? png.data.write(to: directory.appendingPathComponent(name))) != nil else { return }
            insert(ClipItem(date: Date(), imageFile: name, imageSize: png.size))
        }
    }

    private func pngData(from board: NSPasteboard) -> (data: Data, size: String)? {
        guard let raw = board.data(forType: .png) ?? board.data(forType: .tiff),
              let bitmap = NSBitmapImageRep(data: raw),
              let png = bitmap.representation(using: .png, properties: [:]) else { return nil }
        return (png, "\(bitmap.pixelsWide)×\(bitmap.pixelsHigh)")
    }

    private func insert(_ item: ClipItem) {
        items.insert(item, at: 0)
        while items.count > limit { deleteFile(items.removeLast()) }
        save()
    }

    private func purge() {
        let cutoff = Date().addingTimeInterval(-lifetime)
        let expired = items.filter { $0.date < cutoff }
        expired.forEach(deleteFile)
        items.removeAll { $0.date < cutoff }
        while items.count > limit { deleteFile(items.removeLast()) }
        if !expired.isEmpty { save() }
    }

    private func deleteFile(_ item: ClipItem) {
        thumbnails[item.id] = nil
        if let file = item.imageFile { try? FileManager.default.removeItem(at: directory.appendingPathComponent(file)) }
    }

    private func save() {
        if let data = try? JSONEncoder().encode(items) { try? data.write(to: indexFile) }
    }
}
